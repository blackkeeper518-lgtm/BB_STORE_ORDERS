-- ST CHAT SCHEMA = BB CHAT SCHEMA
-- เปลี่ยน chat_link_key จากคีย์ข้อความเป็นคีย์ห้อง
-- message_row_id เป็น primary key ของแต่ละข้อความ
-- message_id เป็น unique key สำหรับกันข้อความ Meta ซ้ำ
-- รันใน Supabase โปรเจกต์ ST_CHAT หลังตรวจ duplicate message_id แล้ว

begin;

-- ============================================================
-- 1) ตรวจ duplicate message_id ก่อนเปิด unique index
-- ============================================================
-- หาก query ด้านล่างคืนแถว ให้แก้ duplicate ก่อนรันต่อ:
-- select message_id, count(*)
-- from public."Pg_Chat⭐BINARY_xXx_STAR"
-- where message_id is not null
-- group by message_id
-- having count(*) > 1;
--
-- select message_id, count(*)
-- from public."Cust_Chat⭐BINARY_xXx_STAR"
-- where message_id is not null
-- group by message_id
-- having count(*) > 1;

-- ============================================================
-- 2) Rebuild row key ให้เป็น bigint identity แบบ BB
--    รองรับ ST เดิมที่ message_row_id เป็น text
-- ============================================================

alter table public."Pg_Chat⭐BINARY_xXx_STAR"
  add column if not exists message_row_id_bb bigint
  generated by default as identity;

alter table public."Cust_Chat⭐BINARY_xXx_STAR"
  add column if not exists message_row_id_bb bigint
  generated by default as identity;

-- ลบ primary key เดิม ไม่ว่าจะชื่ออะไร
 do $$
declare
  pk_name text;
begin
  select con.conname into pk_name
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace ns on ns.oid = rel.relnamespace
  where ns.nspname = 'public'
    and rel.relname = 'Pg_Chat⭐BINARY_xXx_STAR'
    and con.contype = 'p';
  if pk_name is not null then
    execute format('alter table public."Pg_Chat⭐BINARY_xXx_STAR" drop constraint %I', pk_name);
  end if;
end $$;

do $$
declare
  pk_name text;
begin
  select con.conname into pk_name
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace ns on ns.oid = rel.relnamespace
  where ns.nspname = 'public'
    and rel.relname = 'Cust_Chat⭐BINARY_xXx_STAR'
    and con.contype = 'p';
  if pk_name is not null then
    execute format('alter table public."Cust_Chat⭐BINARY_xXx_STAR" drop constraint %I', pk_name);
  end if;
end $$;

-- ชื่อเดิมเป็น text ใน ST จึงถอดออกหลังสร้างเลข identity ใหม่
alter table public."Pg_Chat⭐BINARY_xXx_STAR"
  drop column if exists message_row_id;

alter table public."Cust_Chat⭐BINARY_xXx_STAR"
  drop column if exists message_row_id;

alter table public."Pg_Chat⭐BINARY_xXx_STAR"
  rename column message_row_id_bb to message_row_id;

alter table public."Cust_Chat⭐BINARY_xXx_STAR"
  rename column message_row_id_bb to message_row_id;

alter table public."Pg_Chat⭐BINARY_xXx_STAR"
  add constraint "Pg_Chat⭐BINARY_xXx_STAR_message_pkey"
  primary key (message_row_id);

alter table public."Cust_Chat⭐BINARY_xXx_STAR"
  add constraint "Cust_Chat⭐BINARY_xXx_STAR_message_pkey"
  primary key (message_row_id);

-- ============================================================
-- 3) Index แบบ BB
-- ============================================================

create index if not exists "Pg_Chat⭐BINARY_xXx_STAR_room_idx"
  on public."Pg_Chat⭐BINARY_xXx_STAR"
  using btree (chat_link_key, thread_id, occurred_at);

create index if not exists "Cust_Chat⭐BINARY_xXx_STAR_room_idx"
  on public."Cust_Chat⭐BINARY_xXx_STAR"
  using btree (chat_link_key, thread_id, occurred_at);

create index if not exists "Pg_Chat⭐BINARY_xXx_STAR_message_idx"
  on public."Pg_Chat⭐BINARY_xXx_STAR"
  using btree (message_id)
  where message_id is not null;

create index if not exists "Cust_Chat⭐BINARY_xXx_STAR_message_idx"
  on public."Cust_Chat⭐BINARY_xXx_STAR"
  using btree (message_id)
  where message_id is not null;

create unique index if not exists "Pg_Chat⭐BINARY_xXx_STAR_message_id_uidx"
  on public."Pg_Chat⭐BINARY_xXx_STAR"
  using btree (message_id)
  where message_id is not null;

create unique index if not exists "Cust_Chat⭐BINARY_xXx_STAR_message_id_uidx"
  on public."Cust_Chat⭐BINARY_xXx_STAR"
  using btree (message_id)
  where message_id is not null;

create index if not exists "Pg_Chat⭐BINARY_xXx_STAR_occurred_at_row_idx"
  on public."Pg_Chat⭐BINARY_xXx_STAR"
  using btree (occurred_at, message_row_id);

create index if not exists "Cust_Chat⭐BINARY_xXx_STAR_occurred_at_row_idx"
  on public."Cust_Chat⭐BINARY_xXx_STAR"
  using btree (occurred_at, message_row_id);

create index if not exists ix_cust_chat_phone
  on public."Cust_Chat⭐BINARY_xXx_STAR" using btree (phone);

create index if not exists ix_chat_customer_chat_link_key
  on public."Cust_Chat⭐BINARY_xXx_STAR" using btree (chat_link_key);

create index if not exists ix_pg_chat_phone
  on public."Pg_Chat⭐BINARY_xXx_STAR" using btree (phone);

create index if not exists ix_chat_page_chat_link_key
  on public."Pg_Chat⭐BINARY_xXx_STAR" using btree (chat_link_key);

commit;

