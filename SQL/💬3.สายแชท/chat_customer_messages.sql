create table public.chat_page_messages (
  id bigint generated by default as identity not null,
  chat_link_key text null,
  page_id text not null,
  page_name text null,
  portal_key text null,
  assigned_agent text null,
  assigned_hashtag text null,
  conversation_id text null,
  thread_id text not null default ''::text,
  customer_id text null,
  customer_name text null,
  recipient_id text null,
  recipient_name text null,
  message_id text null,
  speaker text null,
  is_sent boolean null default false,
  "time" timestamp with time zone null,
  time_th text null,
  message_time_display text null,
  created_at timestamp with time zone not null default now(),
  has_attachment boolean null default false,
  attachment_type text null,
  attachment_url text null,
  attachment_urls jsonb not null default '[]'::jsonb,
  attachments_raw jsonb not null default '[]'::jsonb,
  sticker_url text null,
  shares_link text null,
  chat_age_hours numeric null,
  is_within_24h boolean null default true,
  can_send_standard boolean null default true,
  is_24h_window_valid boolean null default true,
  messaging_tag_required text null,
  dedupe_key text null,
  sync_status text null default 'READY_TO_SAVE'::text,
  "threadId" text null,
  occurred_at timestamp with time zone null default now(),
  customer_chat_age_hours text null,
  send_facebook_route text null,
  message_text text null,
  drakside_tracking_message text null,
  tracking_number text null,
  parcel_status_emoji text null,
  facebook_tracking_message text null,
  upsert_key text null,
  order_number text null,
  order_number_display text null,
  order_time_display text null,
  page_latest_message text null,
  page_message_time_th text null,
  customer_latest_message text null,
  customer_message_time_th text null,
  constraint chat_page_messages_pkey primary key (id),
  constraint chat_page_messages_message_id_key unique (message_id),
  constraint ux_chat_page_messages_dedupe_key unique (dedupe_key)
) TABLESPACE pg_default;

create index IF not exists idx_chat_page_room on public.chat_page_messages using btree (page_id, thread_id, "time" desc, id desc) TABLESPACE pg_default;

create index IF not exists idx_chat_page_speaker on public.chat_page_messages using btree (page_id, speaker) TABLESPACE pg_default;

create unique INDEX IF not exists ux_chat_page_message_id on public.chat_page_messages using btree (message_id) TABLESPACE pg_default;

create unique INDEX IF not exists ux_chat_page_dedupe_key on public.chat_page_messages using btree (dedupe_key) TABLESPACE pg_default;

create index IF not exists ix_chat_page_messages_chat_link_key on public.chat_page_messages using btree (chat_link_key) TABLESPACE pg_default;

create index IF not exists ix_chat_page_messages_chat_link_key_valid on public.chat_page_messages using btree (chat_link_key) TABLESPACE pg_default
where
  (
    NULLIF(btrim(chat_link_key), ''::text) is not null
  );

create unique INDEX IF not exists chat_page_messages_dedupe_key_uidx on public.chat_page_messages using btree (dedupe_key) TABLESPACE pg_default
where
  (NULLIF(btrim(dedupe_key), ''::text) is not null);

create index IF not exists chat_page_messages_chat_link_key_idx on public.chat_page_messages using btree (chat_link_key) TABLESPACE pg_default;