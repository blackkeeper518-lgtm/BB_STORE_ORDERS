UNION ALL
SELECT 'BB_SENT_HISTORY', COUNT(*) FROM public.vw_bb_telegram_web_history
UNION ALL
SELECT 'ST_SEND', COUNT(*) FROM public.vw_st_telegram_web_queue
UNION ALL
SELECT 'ST_SENT_HISTORY', COUNT(*) FROM public.vw_st_telegram_web_history;
