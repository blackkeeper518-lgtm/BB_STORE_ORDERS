-- ============================================================================
-- BLACKBOX ALERT CENTER · MAIN ALERT SQL
-- ============================================================================
-- BB STORE / Supabase PostgreSQL
-- ไฟล์เดียวจบ: ตาราง + ห้อง 4 ห้อง + ป้ายเตือน + หลักฐาน + รอยมือ + View
--
-- หลักการ:
--   1) ไม่ลบ bb_orders และไม่เขียนทับหลักฐานต้นทาง
--   2) ทุกป้ายเตือนมีปลายทางว่าต้องไปห้องไหน
--   3) ทุกการตัดสินใจกลายเป็นรอยมือย้อนกลับได้
--   4) ใช้ room_key เป็นตัวเลือกห้อง (dropdown) ในหน้าเว็บได้ทันที
--
-- ห้องที่ล็อกไว้ 4 ห้อง:
--   BLACKBOX_ALERT_CENTER = ศูนย์ป้ายเตือนกลาง (ห้องหลักของไฟล์นี้)
--   ORDER_CONTROL          = ห้องออเดอร์หลัก
--   BLACKBOX_ROOM          = ห้องแกะรอยออเดอร์
--   TELEGRAM_ROOM          = ห้องคุมการส่ง
--
-- หมายเหตุเรื่อง DROP:
--   DROP VIEW เป็นการรีบิลด์ View เท่านั้น ไม่แตะข้อมูลตารางจริง
--   ห้ามใส่ DROP TABLE ในไฟล์นี้ เพราะป้ายเตือนและรอยมือต้องอยู่รอด
-- ============================================================================

BEGIN;

-- --------------------------------------------------------------------------
-- 0) DROP เฉพาะ View เพื่อให้รันไฟล์ซ้ำได้
-- --------------------------------------------------------------------------
