-- --------------------------------------------------------------------------
-- 8) VIEW: BLACKBOX ALERT CENTER · ตารางหลักหน้าเว็บ
-- --------------------------------------------------------------------------
CREATE VIEW public.vw_blackbox_alert_center AS
SELECT
  a.alert_id,
  a.source_event_id,
  a.source_system,
  a.alert_type,
  a.severity,
  a.headline,
  a.reason,
  a.required_action,
  a.status,
  a.order_id,
  a.upsert_key,
  a.order_number,
  a.page_name,
  a.customer_name,
  a.phone,
  a.thread_id,
  a.occurred_at,
  a.detected_at,
  a.order_date,
  a.cod_before,
  a.cod_after,
  a.product_before,
  a.product_after,
  a.quantity_before,
  a.quantity_after,
  a.change_decision_minutes,
  a.duplicate_group_id,
  a.duplicate_reason,
  a.evidence_summary,
  a.destination_room,
  r.room_name AS destination_room_name,
  r.room_name_th AS destination_room_th,
  r.room_color AS destination_room_color,
  r.room_icon AS destination_room_icon,
  a.destination_url,
  a.assigned_to,
  a.closed_at,
  a.closed_by,
  a.close_reason,
  a.created_at,
  a.updated_at,
  CASE a.severity
    WHEN 'CRITICAL' THEN 'กั้นก่อนส่ง'
    WHEN 'REVIEW' THEN 'รอตัดสินใจ'
    WHEN 'INCOMPLETE' THEN 'ข้อมูลพร่อง'
    ELSE 'แจ้งสถานะ'
  END AS severity_th,
  CASE a.alert_type
    WHEN 'DUPLICATE_FROM_FOUR' THEN 'ซ้ำจากโฟร์'
    WHEN 'QUESTION_NOT_ORDER' THEN 'ถามไม่ใช่สั่ง'
    WHEN 'CUSTOMER_CHANGED_PRODUCT' THEN 'ลูกค้าเปลี่ยนของ'
    WHEN 'MIDDLE_BUCKET_RISK' THEN 'ก้อนกลางมีรอย'
    WHEN 'INCOMPLETE_DATA' THEN 'เบอร์พร่อง / ข้อมูลไม่ครบ'
    WHEN 'PRODUCT_MISMATCH' THEN 'สินค้าไม่ตรง'
    WHEN 'COD_MISMATCH' THEN 'ยอดกำลังซ้อน'
    WHEN 'DELIVERY_FAILED' THEN 'ส่งไม่ออก'
    WHEN 'DELIVERY_SENT' THEN 'ส่งแล้ว'
    WHEN 'SYSTEM_SILENT' THEN 'ระบบเงียบผิดปกติ'
    ELSE 'เฝ้าดู'
  END AS alert_type_th,
  CASE WHEN a.product_before IS NOT NULL OR a.product_after IS NOT NULL THEN
    concat_ws(' → ', COALESCE(a.product_before, 'รอบแรกไม่ระบุ'), COALESCE(a.product_after, 'รายการล่าสุดไม่ระบุ'))
  END AS change_route_text,
  CASE WHEN a.cod_before IS NOT NULL OR a.cod_after IS NOT NULL THEN
    concat_ws(' → ', COALESCE(a.cod_before::text, '—'), COALESCE(a.cod_after::text, '—'))
  END AS cod_route_text,
  COALESCE(ev.evidence_count, 0)::integer AS evidence_count,
  COALESCE(dec.decision_count, 0)::integer AS decision_count,
  dec.last_decision_code,
  dec.last_decision_at
FROM public.blackbox_alert_events a
LEFT JOIN public.blackbox_rooms r
  ON r.room_key = a.destination_room
LEFT JOIN LATERAL (
  SELECT count(*)::integer AS evidence_count
  FROM public.blackbox_alert_evidence e
  WHERE e.alert_id = a.alert_id
) ev ON true
LEFT JOIN LATERAL (
  SELECT
    count(*)::integer AS decision_count,
    (array_agg(d.decision_code ORDER BY d.created_at DESC))[1] AS last_decision_code,
    max(d.created_at) AS last_decision_at
  FROM public.blackbox_alert_decisions d
  WHERE d.alert_id = a.alert_id
) dec ON true;

-- --------------------------------------------------------------------------
-- 9) VIEW: HOT FEED · ฝั่งนาฟิกา/ป้ายไฟ
-- --------------------------------------------------------------------------
CREATE VIEW public.vw_blackbox_hot_feed AS
SELECT
  alert_id,
  severity,
  severity_th,
  alert_type,
  alert_type_th,
  headline,
  page_name,
  order_number,
  destination_room,
  destination_room_name,
  detected_at,
  status,
  evidence_count,
  CASE severity WHEN 'CRITICAL' THEN 1 WHEN 'REVIEW' THEN 2 WHEN 'INCOMPLETE' THEN 3 ELSE 4 END AS heat_rank
FROM public.vw_blackbox_alert_center
WHERE status IN ('NEW', 'ACKNOWLEDGED', 'IN_REVIEW', 'ROUTED')
ORDER BY heat_rank, detected_at DESC;

