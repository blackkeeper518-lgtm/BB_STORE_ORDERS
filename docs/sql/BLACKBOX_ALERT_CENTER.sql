-- --------------------------------------------------------------------------
-- 2) ALERT EVENTS · ตารางป้ายเตือนหลัก
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.blackbox_alert_events (
  alert_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_event_id text,
  source_system text NOT NULL DEFAULT 'n8n',
  source_payload jsonb NOT NULL DEFAULT '{}'::jsonb,

  -- ป้ายเตือน
  alert_type text NOT NULL DEFAULT 'WATCH',
  severity text NOT NULL DEFAULT 'INFO',
  headline text NOT NULL,
  reason text,
  required_action text,
  status text NOT NULL DEFAULT 'NEW',

  -- ตัวตนออเดอร์/เพจ/ลูกค้า
  order_id text,
  upsert_key text,
  order_number text,
  page_name text,
  customer_name text,
  phone text,
  thread_id text,

  -- เวลาและเงิน
  occurred_at timestamptz,
  detected_at timestamptz NOT NULL DEFAULT now(),
  order_date text,
  cod_before numeric(12,2),
  cod_after numeric(12,2),

  -- สินค้าก่อนและหลังการเปลี่ยน
  product_before text,
  product_after text,
  quantity_before integer,
  quantity_after integer,
  change_decision_minutes integer,

  -- เหตุผลเฉพาะของระบบ
  duplicate_group_id text,
  duplicate_reason text,
  evidence_summary text,

  -- ทางส่งต่อ
  destination_room text NOT NULL DEFAULT 'BLACKBOX_ALERT_CENTER',
  destination_url text,
  assigned_to text,
  closed_at timestamptz,
  closed_by text,
  close_reason text,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT blackbox_alert_type_ck CHECK (alert_type IN (
    'DUPLICATE_FROM_FOUR',
    'QUESTION_NOT_ORDER',
    'CUSTOMER_CHANGED_PRODUCT',
    'MIDDLE_BUCKET_RISK',
    'INCOMPLETE_DATA',
    'PRODUCT_MISMATCH',
    'COD_MISMATCH',
    'DELIVERY_FAILED',
    'DELIVERY_SENT',
    'SYSTEM_SILENT',
    'WATCH'
  )),
  CONSTRAINT blackbox_severity_ck CHECK (severity IN ('CRITICAL', 'REVIEW', 'INCOMPLETE', 'INFO')),
  CONSTRAINT blackbox_alert_status_ck CHECK (status IN ('NEW', 'ACKNOWLEDGED', 'IN_REVIEW', 'ROUTED', 'RESOLVED', 'DISMISSED')),
  CONSTRAINT blackbox_destination_room_ck CHECK (destination_room IN (
    'BLACKBOX_ALERT_CENTER', 'ORDER_CONTROL', 'BLACKBOX_ROOM', 'TELEGRAM_ROOM'
  ))
);

-- --------------------------------------------------------------------------
-- 3) EVIDENCE · หลักฐานหลายชิ้นต่อหนึ่งป้าย
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.blackbox_alert_evidence (
  evidence_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id bigint NOT NULL REFERENCES public.blackbox_alert_events(alert_id) ON DELETE RESTRICT,
  evidence_type text NOT NULL DEFAULT 'NOTE',
  evidence_label text NOT NULL,
  evidence_text text,
  source_system text,
  source_event_id text,
  evidence_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT blackbox_evidence_type_ck CHECK (evidence_type IN (
    'RAW_PAYLOAD', 'CHAT', 'ORDER', 'SYSTEM_RETRY', 'LOCATION', 'NOTE', 'SCREENSHOT'
  ))
);

-- --------------------------------------------------------------------------
-- 4) DECISIONS · รอยมือการตัดสินใจของคน/ระบบ
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.blackbox_alert_decisions (
  decision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id bigint NOT NULL REFERENCES public.blackbox_alert_events(alert_id) ON DELETE RESTRICT,
  actor_type text NOT NULL DEFAULT 'HUMAN',
  actor_name text,
  decision_code text NOT NULL,
  decision_note text,
  from_status text,
  to_status text NOT NULL,
  destination_room text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT blackbox_actor_type_ck CHECK (actor_type IN ('HUMAN', 'BOT', 'SYSTEM')),
  CONSTRAINT blackbox_decision_code_ck CHECK (decision_code IN (
    'ACKNOWLEDGE', 'HOLD_BEFORE_SEND', 'ROUTE_TO_ORDER_CONTROL',
    'ROUTE_TO_BLACKBOX_ROOM', 'ROUTE_TO_TELEGRAM_ROOM', 'MERGE_CASE',
    'SPLIT_CASE', 'ASK_CUSTOMER', 'MARK_NOT_DUPLICATE', 'RESOLVE', 'DISMISS'
  ))
);

-- --------------------------------------------------------------------------
-- 5) INDEXES · ให้ศูนย์ป้ายเตือนค้นเร็ว
-- --------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_blackbox_alert_live
  ON public.blackbox_alert_events (severity, status, detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_blackbox_alert_order
  ON public.blackbox_alert_events (upsert_key, order_number);
CREATE INDEX IF NOT EXISTS idx_blackbox_alert_destination
  ON public.blackbox_alert_events (destination_room, status, detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_blackbox_alert_duplicate
  ON public.blackbox_alert_events (duplicate_group_id)
  WHERE duplicate_group_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_blackbox_evidence_alert
  ON public.blackbox_alert_evidence (alert_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_blackbox_decisions_alert
  ON public.blackbox_alert_decisions (alert_id, created_at DESC);

-- --------------------------------------------------------------------------
-- 6) UPDATED_AT · แตะเวลาแก้ไขอัตโนมัติ
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.blackbox_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_blackbox_rooms_updated_at ON public.blackbox_rooms;
CREATE TRIGGER trg_blackbox_rooms_updated_at
BEFORE UPDATE ON public.blackbox_rooms
FOR EACH ROW EXECUTE FUNCTION public.blackbox_touch_updated_at();

DROP TRIGGER IF EXISTS trg_blackbox_alert_events_updated_at ON public.blackbox_alert_events;
CREATE TRIGGER trg_blackbox_alert_events_updated_at
BEFORE UPDATE ON public.blackbox_alert_events
FOR EACH ROW EXECUTE FUNCTION public.blackbox_touch_updated_at();

